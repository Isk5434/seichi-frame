test('simulated camera captures a photo and stops stream when leaving camera', async ({ page }) => {
  await page.locator('[data-view=camera]').click();
  await page.locator('#camera-start').click();
  await expect(page.locator('#capture')).toBeEnabled();
  await page.evaluate(() => { window.testTrack = document.querySelector('video').srcObject.getVideoTracks()[0]; });
  await page.locator('#capture').click();
  await expect(page.locator('#own-image')).toBeVisible();
  await expect(page.locator('#status')).toContainText('保存しました');
  expect(await page.evaluate(() => window.testTrack.readyState)).toBe('ended');
  await page.locator('[data-view=camera]').click();
  await page.locator('#camera-start').click();
  await expect(page.locator('#capture')).toBeEnabled();
  await page.evaluate(() => { window.testTrack = document.querySelector('video').srcObject.getVideoTracks()[0]; });
  await page.locator('[data-view=map]').click();
  expect(await page.evaluate(() => window.testTrack.readyState)).toBe('ended');
});
test('camera permission refusal and denied location show useful errors', async ({ page }) => {
  await page.evaluate(() => {
    navigator.mediaDevices.getUserMedia = async () => { throw new DOMException('Denied', 'NotAllowedError'); };
    navigator.geolocation.getCurrentPosition = (_success, error) => error({ code: 1 });
  });
  await page.locator('[data-view=camera]').click();
  await page.locator('#camera-start').click();
  await expect(page.locator('#status')).toContainText('許可されていません');
  await expect(page.locator('#camera-start')).toBeEnabled();
  await page.locator('#locate').click();
  await expect(page.locator('#status')).toContainText('現在地を取得できません');
});
test('mobile fits screen and exposes comparison controls', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(page.locator('#search')).toBeInViewport();
  await page.locator('.spot-card').first().click();
  await expect(page.locator('.add-photo')).toBeInViewport();
  await expect(page.locator('body')).toHaveCSS('overflow-y', 'visible');
  expect(await page.evaluate(() => getComputedStyle(document.body, '::before').position)).toBe('fixed');
  await page.locator('#gallery .photo-card').first().click();
  const preview = page.locator('#photo-preview');
  await expect(preview).toBeVisible();
  await expect(preview).toHaveCSS('width', '390px');
  await expect(preview).toHaveCSS('height', '844px');
  await expect.poll(() => preview.locator('img').evaluate(image => image.naturalWidth)).toBeGreaterThan(0);
  const count = preview.locator('#photo-preview-count');
  await expect(count).toHaveText('1 / 2');
  const touch = await page.context().newCDPSession(page);
  await touch.send('Emulation.setTouchEmulationEnabled', { enabled: true });
  await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 300, y: 350 }] });
  await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 100, y: 350 }] });
  await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await expect(count).toHaveText('2 / 2');
  await page.keyboard.press('ArrowLeft');
  await expect(count).toHaveText('1 / 2');
  await preview.getByRole('button', { name: '閉じる' }).click();
  await expect(preview).toBeHidden();
  await page.locator('[data-view=compare]').click();
  await page.locator('[data-mode=overlay]').click();
  await expect(page.locator('#opacity')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true });
});
